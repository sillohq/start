class PackagesSection(Section):
    """Enabled Sillo package groups."""

    groups: list[str] = Field(default_factory=list)

    @field_validator("groups")
    @classmethod
    def _dedupe(cls, value: list[str]) -> list[str]:
        """Drop duplicates while preserving install order."""
        seen: set[str] = set()
        ordered: list[str] = []
        for name in value:
            if name not in seen:
                seen.add(name)
                ordered.append(name)
        return ordered


class DevelopmentSection(Section):
    """Commands the orchestrator runs for ``sillo-start dev``.

    These are stored as strings so a developer can edit them without touching
    Sillo Start. They default to real, existing commands: the framework ships
    no CLI of its own, so the backend runs under uvicorn and the worker and
    scheduler run generated scripts.
    """

    backend_command: str = Field(default="uvicorn app.main:app --reload")
    frontend_command: str = Field(default="")
    worker_command: str = Field(default="")
    scheduler_command: str = Field(default="")
    extra_services: dict[str, str] = Field(default_factory=dict)


class SilloManifest(BaseModel):
    """The whole of ``sillo.toml``."""

    model_config = ConfigDict(extra="allow", validate_assignment=True)

    project: ProjectSection
    application: ApplicationSection = Field(default_factory=ApplicationSection)
    database: DatabaseSection = Field(default_factory=DatabaseSection)
    auth: AuthSection = Field(default_factory=AuthSection)
    authorization: AuthorizationSection = Field(default_factory=AuthorizationSection)
    admin: AdminSection = Field(default_factory=AdminSection)
    inertia: InertiaSection = Field(default_factory=InertiaSection)
    queue: QueueSection = Field(default_factory=QueueSection)
    scheduler: SchedulerSection = Field(default_factory=SchedulerSection)
    cache: CacheSection = Field(default_factory=CacheSection)
    session: SessionSection = Field(default_factory=SessionSection)
    mail: MailSection = Field(default_factory=MailSection)
    storage: StorageSection = Field(default_factory=StorageSection)
    api: ApiSection = Field(default_factory=ApiSection)
    tooling: ToolingSection = Field(default_factory=ToolingSection)
    packages: PackagesSection = Field(default_factory=PackagesSection)
    development: DevelopmentSection = Field(default_factory=DevelopmentSection)

    @model_validator(mode="after")
    def _admin_implies_sessions(self) -> SilloManifest:
        """Turn sessions on whenever the admin panel is enabled.

        The admin's default backend (``sillo.admin.auth.SessionAuth``) reads
        and writes ``request.session``; with no session middleware installed
        ``getattr(request, "session", None)`` is None, so ``authenticate``
        always returns False. The login form then appears to accept the
        password and bounces straight back to itself, forever, with nothing
        logged — so this is recorded in the manifest rather than papered over
        in the template, keeping sillo.toml an honest description of the app.
        """
        if self.admin.enabled and not self.session.enabled:
            object.__setattr__(self.session, "enabled", True)
        return self

    # -- convenience ----------------------------------------------------

    @property
    def name(self) -> str:
        """The project name."""
        return self.project.name

    @property
    def package(self) -> str:
        """The importable package name."""
        return self.project.package

    @property
    def uses_record(self) -> bool:
        """Whether the Record ORM is configured."""
        return self.database.enabled and self.database.orm == ORM.RECORD

    @property
    def uses_sessions(self) -> bool:
        """Whether the app needs session middleware installed.

        Derived rather than read straight off ``session.enabled`` because the
        admin panel requires sessions whether or not the operator asked for
        them, and blueprints flip ``admin.enabled`` after the manifest has been
        validated — so the manifest validator alone would miss those.
        """
        return self.session.enabled or self.admin.enabled

    @property
    def needs_redis(self) -> bool:
        """Whether any enabled feature requires a Redis server."""
        return (
            (self.queue.enabled and self.queue.driver == QueueDriver.REDIS)
            or (self.cache.enabled and self.cache.driver == CacheDriver.REDIS)
            or (self.session.enabled and self.session.driver == SessionDriver.REDIS)
        )

    @property
    def needs_web_routes(self) -> bool:
        """Whether a browser-facing router should be generated.

        True for anything that serves pages: an Inertia frontend renders
        through a web router, and a project without an API surface has nothing
        else to route with.
        """
        return self.inertia.enabled or not self.api.enabled

    @property
    def needs_database_server(self) -> bool:
        """Whether the database runs as a separate server process."""
        return self.database.enabled and self.database.driver in (
            DatabaseDriver.POSTGRES,
            DatabaseDriver.MYSQL,
        )

    def has_group(self, group: str) -> bool:
        """Report whether a package group is enabled."""
        return group in self.packages.groups

    def add_group(self, group: str) -> bool:
        """Enable a package group.

        Returns:
            True when the group was newly added.
        """
        if group in self.packages.groups:
            return False
        self.packages.groups = [*self.packages.groups, group]
        return True

    def remove_group(self, group: str) -> bool:
        """Disable a package group.

        Returns:
            True when the group was present and removed.
        """
        if group not in self.packages.groups:
            return False
        self.packages.groups = [name for name in self.packages.groups if name != group]
        return True

    def to_dict(self) -> dict[str, Any]:
        """Serialise for TOML writing, with enums flattened to their values."""
        return self.model_dump(mode="json", exclude_none=True)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> SilloManifest:
        """Build a manifest from parsed TOML data."""
        return cls.model_validate(data)
