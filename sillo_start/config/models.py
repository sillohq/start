class AdminSection(Section):
    """Sillo admin panel configuration."""

    enabled: bool = False
    prefix: str = Field(default="/admin")
    title: str = Field(default="")
    user_management: bool = True
    role_management: bool = False

    @field_validator("prefix")
    @classmethod
    def _normalise_prefix(cls, value: str) -> str:
        value = "/" + value.strip("/")
        return value.rstrip("/") or "/admin"


