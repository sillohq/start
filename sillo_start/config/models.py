"""Pydantic models for ``sillo.toml``.

The manifest is the authoritative description of a generated project: what the
application is, which features are switched on, and how to run it. Every other
subsystem reads it rather than sniffing the filesystem, so ``add``, ``remove``,
``dev``, ``doctor`` and ``upgrade`` all agree on the project's shape.

The models are permissive about unknown keys on purpose. A project generated by
a newer Sillo Start, or extended by a plugin that owns its own section, must
still load in an older tool rather than failing validation.
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from ..utils.naming import is_valid_project_name, package_name_for
from .defaults import (
    DEFAULT_BACKEND_PORT,
    DEFAULT_FRONTEND_PORT,
    ORM,
    SILLO_VERSION_SPEC,
    AppType,
    AuthStrategy,
    CacheDriver,
    DatabaseDriver,
    FrontendPackageManager,
    InertiaAdapter,
    MailDriver,
    PythonPackageManager,
    QueueDriver,
    SessionDriver,
    StorageDriver,
)

#: Manifest schema version. Bumped when a change needs migration on upgrade.
MANIFEST_VERSION = 1


class Section(BaseModel):
    """Base for every manifest section.

    ``extra="allow"`` is what lets a plugin add keys to a section, and lets an
    older Sillo Start read a manifest written by a newer one without dropping
    the keys it does not understand.
    """

    model_config = ConfigDict(extra="allow", validate_assignment=True, use_enum_values=True)


class ProjectSection(Section):
    """Identity of the project itself."""

    name: str = Field(description="Project name, also the directory name.")
    version: str = Field(default="0.1.0", description="Application version.")
    description: str = Field(default="", description="One-line project summary.")
    python: str = Field(default=">=3.11", description="Required Python range.")
    sillo_version: str = Field(
        default=SILLO_VERSION_SPEC,
        description="Version specifier for the sillo-framework dependency.",
    )
    package: str = Field(
        default="",
        description="Importable package name. Derived from the project name when blank.",
    )
    manifest_version: int = Field(
        default=MANIFEST_VERSION,
        description="Manifest schema version, used by `sillo-start upgrade`.",
    )
    created_with: str = Field(
        default="",
        description="Sillo Start version that generated the project.",
    )

    @field_validator("name")
    @classmethod
    def _validate_name(cls, value: str) -> str:
        if not is_valid_project_name(value):
            raise ValueError(
                f"'{value}' is not a valid project name. Use a letter followed by "
                "letters, digits, dots, dashes or underscores."
            )
        return value

    @model_validator(mode="after")
    def _derive_package(self) -> ProjectSection:
        if not self.package:
            # Assigning through object.__setattr__ avoids re-triggering
            # validate_assignment, which would recurse through this validator.
            object.__setattr__(self, "package", package_name_for(self.name))
        return self


class ApplicationSection(Section):
    """How the application is shaped and launched."""

    type: AppType = Field(default=AppType.API)
    entrypoint: str = Field(
        default="app.main:app",
        description="ASGI entrypoint in `module:attribute` form.",
    )
    host: str = Field(default="127.0.0.1")
    port: int = Field(default=DEFAULT_BACKEND_PORT, ge=1, le=65535)


class DatabaseSection(Section):
    """Database connection and ORM configuration."""

    enabled: bool = False
    driver: DatabaseDriver = DatabaseDriver.NONE
    orm: ORM = ORM.NONE
    migrations_path: str = Field(default="database/migrations")
    models_module: str = Field(
        default="database.models",
        description="Dotted module Record scans for models.",
    )

    @property
    def migrations_module(self) -> str:
        """``migrations_path`` as a dotted module path.

        Tortoise locates migrations by import, not by directory, so the app
        config needs the module form of the same location.
        """
        return self.migrations_path.strip("/").replace("/", ".")

    @model_validator(mode="after")
    def _coherent(self) -> DatabaseSection:
        """Keep ``enabled`` and ``driver`` from contradicting each other."""
        if self.enabled and self.driver == DatabaseDriver.NONE:
            object.__setattr__(self, "driver", DatabaseDriver.SQLITE)
        if not self.enabled:
            object.__setattr__(self, "driver", DatabaseDriver.NONE)
            object.__setattr__(self, "orm", ORM.NONE)
        return self


class AuthSection(Section):
    """Authentication feature switches."""

    enabled: bool = False
    strategy: AuthStrategy = AuthStrategy.NONE
    user_model: str = Field(
        default="database.models.user.User",
        description="Dotted path to the project's user model.",
    )
    registration: bool = True
    login: bool = True
    logout: bool = True
    password_reset: bool = False
    email_verification: bool = False
    remember_me: bool = False
    middleware: bool = True
    routes: bool = True
    service_layer: bool = True
    tests: bool = True

    @model_validator(mode="after")
    def _coherent(self) -> AuthSection:
        """Keep the strategy consistent with whether auth is on at all.

        The sub-switches are deliberately left alone. Zeroing them here would
        be destructive: ``enabled`` is flipped on after construction by
        blueprints and by the admin's implications, and the switches would
        have already been cleared by the first validation pass with no way to
        tell a real ``registration = false`` from a side effect. Consumers ask
        for ``auth.enabled and auth.routes`` instead.
        """
        if not self.enabled:
            object.__setattr__(self, "strategy", AuthStrategy.NONE)
        elif self.strategy == AuthStrategy.NONE:
            object.__setattr__(self, "strategy", AuthStrategy.SESSION)
        return self


