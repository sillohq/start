class QueueSection(Section):
    """Background job processing."""

    enabled: bool = False
    driver: QueueDriver = QueueDriver.NONE
    name: str = Field(default="default", description="Default queue name.")
    concurrency: int = Field(default=4, ge=1, le=256)

    @model_validator(mode="after")
    def _coherent(self) -> QueueSection:
        if not self.enabled:
            object.__setattr__(self, "driver", QueueDriver.NONE)
        elif self.driver == QueueDriver.NONE:
            object.__setattr__(self, "driver", QueueDriver.MEMORY)
        return self


